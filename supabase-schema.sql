create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  cat text not null,
  brand text not null default 'AYMELEK',
  orig numeric(10,2) not null check (orig > 0),
  disc int not null default 0 check (disc between 0 and 90),
  colors jsonb not null default '[]',
  stock jsonb not null default '{}',
  is_new boolean not null default false,
  best boolean not null default false,
  images jsonb not null default '[]',
  descr text not null default '',
  mat text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  customer_name text not null,
  email text not null,
  phone text not null,
  country text not null,
  city text not null,
  address text not null,
  postal text not null,
  payment_method text not null check (payment_method in ('kapida','havale')),
  status text not null default 'beklemede'
    check (status in ('beklemede','hazirlaniyor','kargoda','teslim','iptal','iade_talebi','iade')),
  subtotal numeric(10,2) not null,
  discount numeric(10,2) not null,
  shipping numeric(10,2) not null,
  total numeric(10,2) not null
);
create index if not exists orders_created_idx on public.orders(created_at);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  name text not null,
  size text not null,
  color text not null,
  qty int not null check (qty > 0),
  unit_price numeric(10,2) not null
);

-- Yönetici kontrolü
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid())
$$;

-- Satır düzeyi güvenlik (RLS)
alter table public.products enable row level security;
alter table public.admins enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "urunleri herkes gorur" on public.products for select using (true);
create policy "urun ekle" on public.products for insert with check (public.is_admin());
create policy "urun guncelle" on public.products for update using (public.is_admin()) with check (public.is_admin());
create policy "urun sil" on public.products for delete using (public.is_admin());

create policy "kendi admin kaydi" on public.admins for select using (user_id = auth.uid());

create policy "siparisleri admin gorur" on public.orders for select using (public.is_admin());
create policy "siparisi admin gunceller" on public.orders for update using (public.is_admin()) with check (public.is_admin());
create policy "kalemleri admin gorur" on public.order_items for select using (public.is_admin());

-- Sipariş oluşturma: fiyatlar ve stok SUNUCUDA hesaplanır, müşteri fiyatı değiştiremez.
create or replace function public.place_order(
  p_name text, p_email text, p_phone text, p_country text, p_city text,
  p_address text, p_postal text, p_payment text, p_items jsonb
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  it jsonb; pr public.products%rowtype; unit numeric; have int; q int;
  sub numeric := 0; tot numeric := 0; ship numeric; oid bigint;
begin
  if coalesce(trim(p_name),'')='' or coalesce(trim(p_email),'')='' or coalesce(trim(p_phone),'')=''
     or coalesce(trim(p_address),'')='' or coalesce(trim(p_city),'')='' then
    raise exception 'Eksik bilgi';
  end if;
  if p_payment not in ('kapida','havale') then raise exception 'Gecersiz odeme yontemi'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Sepet bos'; end if;

  -- 1. geçiş: doğrula ve toplamları hesapla
  for it in select * from jsonb_array_elements(p_items) loop
    q := (it->>'qty')::int;
    if q is null or q < 1 or q > 20 then raise exception 'Gecersiz adet'; end if;
    select * into pr from public.products where id = (it->>'id')::bigint;
    if not found then raise exception 'Urun bulunamadi'; end if;
    have := coalesce((pr.stock ->> (it->>'size'))::int, 0);
    if have < q then raise exception 'Yetersiz stok: %', pr.name; end if;
    unit := round(pr.orig * (100 - pr.disc) / 100);
    sub := sub + pr.orig * q;
    tot := tot + unit * q;
  end loop;

  ship := case when tot >= 100 then 0 else 4.90 end;

  insert into public.orders(customer_name,email,phone,country,city,address,postal,payment_method,subtotal,discount,shipping,total)
  values (trim(p_name),trim(p_email),trim(p_phone),trim(p_country),trim(p_city),trim(p_address),trim(p_postal),p_payment,
          sub, sub - tot, ship, tot + ship)
  returning id into oid;

  -- 2. geçiş: kalemleri yaz ve stoğu düş
  for it in select * from jsonb_array_elements(p_items) loop
    q := (it->>'qty')::int;
    select * into pr from public.products where id = (it->>'id')::bigint for update;
    unit := round(pr.orig * (100 - pr.disc) / 100);
    insert into public.order_items(order_id,product_id,name,size,color,qty,unit_price)
    values (oid, pr.id, pr.name, it->>'size', coalesce(it->>'color','-'), q, unit);
    update public.products
      set stock = jsonb_set(stock, array[it->>'size'], to_jsonb((stock ->> (it->>'size'))::int - q))
      where id = pr.id;
  end loop;
  return oid;
end $$;

grant execute on function public.place_order(text,text,text,text,text,text,text,text,jsonb) to anon, authenticated;

-- Satış raporu (yalnızca yöneticiler veri görür): p = 'day' | 'week' | 'month'
create or replace function public.sales_report(p text) returns table(
  period date, orders bigint, revenue numeric, refunded numeric, pending bigint
) language sql stable security definer set search_path = public as $$
  select date_trunc(case when p in ('day','week','month') then p else 'day' end, created_at)::date,
         count(*),
         coalesce(sum(total) filter (where status not in ('iptal','iade','iade_talebi')), 0),
         coalesce(sum(total) filter (where status = 'iade'), 0),
         count(*) filter (where status = 'beklemede')
  from public.orders
  where public.is_admin()
  group by 1 order by 1 desc limit 60
$$;
grant execute on function public.sales_report(text) to authenticated;

